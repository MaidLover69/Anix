/**
 * The rows of the Home screen: the five built-in rows, plus rows the user adds in
 * Settings › Appearance (airing this week, one list status, one playlist or collection).
 * Each row can be moved and hidden; added rows can also be removed. Kept free of React so a
 * node script can check it; labels are i18n keys.
 */

export const HOME_ROWS = [
  { id: 'continue', labelKey: 'homeRows.continue' },
  { id: 'because', labelKey: 'homeRows.because' },
  { id: 'trending', labelKey: 'homeRows.trending' },
  { id: 'popular', labelKey: 'homeRows.popular' },
  { id: 'top_rated', labelKey: 'homeRows.topRated' },
] as const;

export type BuiltInRowId = (typeof HOME_ROWS)[number]['id'];

/** The list statuses that can become a Home row. */
export const STATUS_ROWS = ['CURRENT', 'PLANNING', 'PAUSED'] as const;
export type StatusRowValue = (typeof STATUS_ROWS)[number];

/** An added row: `airing`, `status:<STATUS>` or `playlist:<playlist id>`. */
export type AddedRowId = 'airing' | `status:${StatusRowValue}` | `playlist:${string}`;
export type HomeRowId = BuiltInRowId | AddedRowId;

const BUILT_IN = HOME_ROWS.map((row) => row.id) as BuiltInRowId[];
// Playlist ids are generated by the app (`pl-<hex>-<hex>-<hex>`); older ones may differ, so any
// short id of safe characters is accepted.
const PLAYLIST_ROW = /^playlist:[A-Za-z0-9_-]{1,64}$/;

export function isBuiltInRow(id: string): id is BuiltInRowId {
  return BUILT_IN.includes(id as BuiltInRowId);
}

export function isHomeRowId(id: unknown): id is HomeRowId {
  if (typeof id !== 'string') return false;
  if (isBuiltInRow(id) || id === 'airing') return true;
  if (id.startsWith('status:')) return STATUS_ROWS.includes(id.slice(7) as StatusRowValue);
  return PLAYLIST_ROW.test(id);
}

/** What a row shows. */
export type RowKind =
  | { kind: 'builtin'; id: BuiltInRowId }
  | { kind: 'airing' }
  | { kind: 'status'; status: StatusRowValue }
  | { kind: 'playlist'; playlistId: string };

export function rowKind(id: HomeRowId): RowKind {
  if (isBuiltInRow(id)) return { kind: 'builtin', id };
  if (id === 'airing') return { kind: 'airing' };
  if (id.startsWith('status:')) return { kind: 'status', status: id.slice(7) as StatusRowValue };
  return { kind: 'playlist', playlistId: id.slice(9) };
}

/**
 * The rows in the saved order. Unknown and repeated ids are dropped; built-in rows the saved
 * order does not name (new in this version) follow in their default order. Settings from 1.4
 * (built-in ids only) give the same five rows in the same order.
 */
export function orderHomeRows(saved: readonly unknown[] | null | undefined): HomeRowId[] {
  const picked = (saved ?? []).filter((id, i, all): id is HomeRowId => isHomeRowId(id) && all.indexOf(id) === i);
  return [...picked, ...BUILT_IN.filter((id) => !picked.includes(id))];
}

/** The rows Home shows: the order without hidden rows. */
export function visibleHomeRows(order: readonly HomeRowId[], hidden: readonly unknown[] | null | undefined): HomeRowId[] {
  const off = new Set((hidden ?? []).filter(isHomeRowId));
  return order.filter((id) => !off.has(id));
}

/** `order` with `id` moved one place up (-1) or down (+1); unchanged at either end. */
export function moveHomeRow(order: readonly HomeRowId[], id: HomeRowId, step: -1 | 1): HomeRowId[] {
  const from = order.indexOf(id);
  const to = from + step;
  if (from < 0 || to < 0 || to >= order.length) return [...order];
  const next = [...order];
  [next[from], next[to]] = [next[to], next[from]];
  return next;
}

/** `order` with an added row at the end; unchanged when it is already there or not valid. */
export function addHomeRow(order: readonly HomeRowId[], id: string): HomeRowId[] {
  if (!isHomeRowId(id) || order.includes(id)) return [...order];
  return [...order, id];
}

/** `order` without an added row. Built-in rows can only be hidden, never removed. */
export function removeHomeRow(order: readonly HomeRowId[], id: HomeRowId): HomeRowId[] {
  return isBuiltInRow(id) ? [...order] : order.filter((row) => row !== id);
}

/** The hidden list with `id` switched: hidden ↔ shown. Invalid ids in the saved list are dropped. */
export function toggleHiddenRow(hidden: readonly unknown[] | null | undefined, id: HomeRowId): HomeRowId[] {
  const current = (hidden ?? []).filter(isHomeRowId);
  return current.includes(id) ? current.filter((row) => row !== id) : [...current, id];
}

/** Playlist rows whose playlist no longer exists are skipped, so a stale row never shows an empty rail. */
export function livePlaylistRow(id: HomeRowId, playlistIds: readonly string[] | undefined): boolean {
  const kind = rowKind(id);
  return kind.kind !== 'playlist' || !playlistIds || playlistIds.includes(kind.playlistId);
}
