/** `line` with each `{name}` replaced by `vars[name]`; an unknown one becomes empty. */
export function fillLine(line: string, vars: Record<string, string | number> = {}): string {
  return line.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : ''));
}
